export type StringKey = keyof typeof S;
const IDX: Record<Locale, number> = { pl: 0, en: 1, ro: 2 };

export function translate(locale: Locale, key: StringKey, vars?: Record<string, string>) {
  let s = S[key][IDX[locale] ?? 0];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

export function useT() {
  const { locale } = useAuth();
  return (key: StringKey, vars?: Record<string, string>) => translate(locale, key, vars);
}

export const localeSuffix = (l: Locale) => (l === "en" ? "En" : l === "ro" ? "Ro" : "Pl");
